type JoinCommand struct {
	cmd                *cobra.Command
	flags              join.Options
	labelGateway       bool
	restConfigProducer *restconfig.Producer
}

var JoinClusterToBroker = join.ClusterToBroker

func init() {
	rootCmd.AddCommand(NewJoinCmd())
}

func NewJoinCmd() *cobra.Command {
	joinCmd := &JoinCommand{
		cmd:                nil,
		restConfigProducer: restconfig.NewProducer(),
	}

	joinCmd.cmd = &cobra.Command{
		Use:   "join",
		Short: "Connect a cluster to an existing broker",
		Args: func(cmd *cobra.Command, args []string) error {
			return joinCmd.checkArguments(args)
		},
		Run: func(_ *cobra.Command, args []string) {
			status := NewReporter()

			brokerInfo, err := broker.ReadInfoFromFile(args[0])
			exit.OnError(status.Error(err, "Error loading the broker information from the given file"))
			status.Success("%s indicates broker is at %s", args[0], brokerInfo.BrokerURL)

			if joinCmd.flags.BrokerURL != "" {
				status.Success("Overriding broker URL using %s", joinCmd.flags.BrokerURL)
				brokerInfo.BrokerURL = joinCmd.flags.BrokerURL
			}

			exit.OnError(joinCmd.restConfigProducer.RunOnSelectedContext(
				func(clusterInfo *cluster.Info, _ string, status reporter.Interface) error {
					return joinCmd.joinInContext(brokerInfo, clusterInfo, status)
				}, status))
		},
	}

	joinCmd.addFlags()
	joinCmd.restConfigProducer.SetupFlags(joinCmd.cmd.Flags())

	return joinCmd.cmd
}

func (c *JoinCommand) checkArguments(args []string) error {
	if len(args) == 0 {
		return errors.New("the broker-info.subm file argument generated by 'subctl deploy-broker' is missing")
	}

	err := cobra.MaximumNArgs(1)(c.cmd, args)
	if err != nil {
		return err
	}

	return checkImageOverrides(c.flags.ImageOverrideArr)
}

