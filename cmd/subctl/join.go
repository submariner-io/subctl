func (c *JoinCommand) joinInContext(brokerInfo *broker.Info, clusterInfo *cluster.Info, status reporter.Interface) error {
	c.determineClusterID(clusterInfo.Name, status)

	ctx := context.TODO()
	networkDetails := getNetworkDetails(ctx, clusterInfo.ClientProducer, status)
	c.flags.ClusterCIDR = determineCIDR("Pod", c.flags.ClusterCIDR, networkDetails.PodCIDRs, status)
	c.flags.ServiceCIDR = determineCIDR("Service", c.flags.ServiceCIDR, networkDetails.ServiceCIDRs, status)

	if brokerInfo.IsConnectivityEnabled() && c.labelGateway {
		possiblyLabelGateway(clusterInfo.ClientProducer.ForKubernetes(), status)
	}

	if c.flags.CustomDomains == nil && brokerInfo.CustomDomains != nil {
		c.flags.CustomDomains = *brokerInfo.CustomDomains
	}

	return JoinClusterToBroker(ctx, brokerInfo, &c.flags, clusterInfo.ClientProducer, status)
}

func possiblyLabelGateway(kubeClient kubernetes.Interface, status reporter.Interface) {
	status.Start("Retrieving the gateway nodes")
	defer status.End()

	gatewayNodes, err := nodes.ListGateways(kubeClient)
	exit.OnError(status.Error(err, "Error retrieving the gateway nodes"))

	if len(gatewayNodes) > 0 {
		fmt.Printf("   There are %d node(s) labeled as gateways:\n", len(gatewayNodes))

		for i := range gatewayNodes {
			fmt.Printf("    - %s\n", gatewayNodes[i])
		}

		return
	}

	// No Gateway nodes are present, get all worker nodes and ask user to select one of them as gateway node
	status.Start("Retrieving all worker nodes")

	workerNodes, err := nodes.GetAllWorkerNames(kubeClient)
	exit.OnError(status.Error(err, "Error listing the worker nodes"))

	status.End()

	if len(workerNodes) == 0 {
		status.Warning("No worker node available to label as the gateway")
		return
	}

	var nodeToLabel string
	if len(workerNodes) == 1 {
		nodeToLabel = workerNodes[0]
	} else {
		nodeToLabel, err = askForGatewayNode(workerNodes)
		exit.OnError(status.Error(err, "Error getting gateway node"))
	}

	status.Start("Labeling node %q as a gateway", nodeToLabel)

	err = nodes.LabelAsGateway(kubeClient, nodeToLabel)
	exit.OnError(status.Error(err, "Error labeling node %q as a gateway", nodeToLabel))
}

func askForGatewayNode(workerNodeNames []string) (string, error) {
	qs := []*survey.Question{
		{
			Name: "node",
			Prompt: NewInputPrompt(&survey.Select{
				Message: "Which node should be used as the gateway?",
				Options: workerNodeNames,
			}),
		},
	}

	answers := struct {
		Node string
	}{}

	err := survey.Ask(qs, &answers)

	return answers.Node, err //nolint:wrapcheck // No need to wrap here
}

func askForClusterID() (string, error) {
	// Missing information
	qs := []*survey.Question{}

	qs = append(qs, &survey.Question{
		Name:   "clusterID",
		Prompt: NewInputPrompt(&survey.Input{Message: "What is your cluster ID?"}),
		Validate: func(val interface{}) error {
			str, ok := val.(string)
			if !ok {
				return nil
			}

			return cluster.IsValidID(str)
		},
	})

	answers := struct {
		ClusterID string
	}{}

	err := survey.Ask(qs, &answers)

	return answers.ClusterID, err //nolint:wrapcheck // No need to wrap here
}

func askForCIDR(name string) (string, error) {
	qs := []*survey.Question{{
		Name: "cidr",
		Prompt: NewInputPrompt(&survey.Input{Message: fmt.Sprintf(
			"What's the %s CIDR for your cluster (comma-separated for multiple)?", name)}),
		Validate: survey.Required,
	}}

	answers := struct {
		Cidr string
	}{}

	err := survey.Ask(qs, &answers)

	return strings.TrimSpace(answers.Cidr), err
}

func (c *JoinCommand) determineClusterID(clusterName string, status reporter.Interface) {
	var err error

	if c.flags.ClusterID == "" {
		c.flags.ClusterID = clusterName

		if err = cluster.IsValidID(c.flags.ClusterID); err != nil {
			c.flags.ClusterID = cluster.SanitizeID(c.flags.ClusterID)
		}
	}

	if c.flags.ClusterID != "" {
		err = cluster.IsValidID(c.flags.ClusterID)
		if err != nil {
			_ = status.Error(err, "Invalid cluster ID")
			c.flags.ClusterID = ""
		}
	}

	if c.flags.ClusterID == "" {
		c.flags.ClusterID, err = askForClusterID()
		exit.OnError(status.Error(err, "Error collecting cluster ID"))
	}
}

func getNetworkDetails(ctx context.Context, clientProducer client.Producer, status reporter.Interface) *network.ClusterNetwork {
	status.Start("Discovering network details")

	networkDetails, err := network.Discover(ctx, clientProducer.ForGeneral(), constants.OperatorNamespace)
	if err != nil {
		status.Warning("Unable to discover network details: %s", err)
	} else if networkDetails == nil {
		status.Warning("No network details discovered")
	}

	status.End()

	if networkDetails != nil {
		networkDetails.Show()
	} else {
		networkDetails = &network.ClusterNetwork{}
	}

	return networkDetails
}

func determineCIDR(name, reqCIDR string, detectedCIDRs []string, status reporter.Interface) string {
	if reqCIDR != "" {
		reqCIDRs := strings.Split(reqCIDR, ",")
		if len(detectedCIDRs) > 0 && !slices.Equivalent(detectedCIDRs, reqCIDRs, slices.Key[string]) {
			status.Warning("The provided %s CIDR for the cluster (%s) does not match the discovered CIDR (%s)",
				name, reqCIDR, strings.Join(detectedCIDRs, ","))
		}
	} else if len(detectedCIDRs) == 0 {
		var err error
		reqCIDR, err = askForCIDR(name)
		exit.OnError(status.Error(err, "Error collecting CIDR"))
	}

	return reqCIDR
}
